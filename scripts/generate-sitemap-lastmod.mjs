#!/usr/bin/env node
/**
 * Regenerates src/data/sitemap-lastmod.ts: the <lastmod> date of every sitemap URL.
 *
 * A page's date is the most recent change to the files that make up its content:
 *   - its page source (src/app/<path>/page.tsx and anything beside it)
 *   - the data files that page imports from "@/data/..."
 *   - for translated pages, that language's dictionary (src/data/locales/<id>.ts)
 * Files with uncommitted edits count as changed today.
 *
 * Run it before deploying:  npm run sitemap:lastmod
 */
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const sh = (cmd) => execSync(cmd, { cwd: ROOT, encoding: 'utf8' }).trim();
const today = new Date().toLocaleDateString('en-CA'); // local YYYY-MM-DD

const routeSrc = readFileSync(join(ROOT, 'src/app/sitemap.xml/route.ts'), 'utf8');
const staticBlock = routeSrc.match(/const STATIC_PATHS = \[([\s\S]*?)\];/);
if (!staticBlock) throw new Error('STATIC_PATHS not found in src/app/sitemap.xml/route.ts');
const staticPaths = [...staticBlock[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const registrySrc = readFileSync(join(ROOT, 'src/data/locales/registry.ts'), 'utf8');
const subpathBlock = registrySrc.match(/TRANSLATED_SUBPATHS = \[([\s\S]*?)\]/);
const subpaths = [...subpathBlock[1].matchAll(/['"]([^'"]*)['"]/g)].map((m) => m[1]);

const localeIds = readdirSync(join(ROOT, 'src/data/locales'))
  .filter((f) => f.endsWith('.ts') && !['index.ts', 'registry.ts', 'types.ts'].includes(f))
  .map((f) => f.replace(/\.ts$/, ''));

/** Last-change date (YYYY-MM-DD) of the newest file in the list. */
function newest(files) {
  let best = '';
  for (const file of files) {
    if (!existsSync(join(ROOT, file))) continue;
    const dirty = sh(`git status --porcelain -- "${file}"`);
    const date = dirty ? today : sh(`git log -1 --format=%cs -- "${file}"`);
    if (date > best) best = date;
  }
  return best;
}

/** The page's own folder plus the "@/data/..." modules its page.tsx imports. */
function pageFiles(appDir) {
  const files = [appDir];
  const page = join(ROOT, appDir, 'page.tsx');
  if (existsSync(page)) {
    for (const m of readFileSync(page, 'utf8').matchAll(/from\s+["']@\/(data\/[^"']+)["']/g)) {
      for (const ext of ['.ts', '.tsx', '/index.ts']) {
        if (existsSync(join(ROOT, 'src', m[1] + ext))) files.push(`src/${m[1]}${ext}`);
      }
    }
  }
  return files;
}

const result = {};

for (const path of staticPaths) {
  result[path] = newest(pageFiles(`src/app${path}`));
}

for (const id of localeIds) {
  const isEnglish = id === 'en';
  for (const sub of subpaths) {
    const urlPath = isEnglish ? sub || '/' : `/${id}${sub}`;
    const appDir = isEnglish ? `src/app${sub}` : `src/app/[locale]${sub}`;
    const files = [`${appDir}/page.tsx`, `src/data/locales/${id}.ts`];
    result[urlPath] = newest(files);
  }
}

const sorted = Object.fromEntries(Object.entries(result).sort(([a], [b]) => a.localeCompare(b)));
const body = Object.entries(sorted)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');

writeFileSync(
  join(ROOT, 'src/data/sitemap-lastmod.ts'),
  `// AUTO-GENERATED by scripts/generate-sitemap-lastmod.mjs. Do not edit by hand.
// Regenerate before deploying: npm run sitemap:lastmod
//
// <lastmod> value per sitemap path: the date the page's content last changed.
// Google only trusts <lastmod> when it is accurate, so it comes from git history
// of the files behind each page, not from the build time.
export const SITEMAP_LASTMOD: Record<string, string> = {
${body}
};
`,
);

console.log(`Wrote ${Object.keys(sorted).length} dates to src/data/sitemap-lastmod.ts`);
